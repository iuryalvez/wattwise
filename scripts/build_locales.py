"""Build the local, synchronous catalog bundle; JSON files are the editable sources."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bundle():
    manifest = json.loads((ROOT / "web/locales/manifest.json").read_text(encoding="utf-8"))
    resources = {locale: {"translation": json.loads((ROOT / "web" / "locales" / f"{locale}.json").read_text(encoding="utf-8"))}
                 for locale in manifest["locales"]}
    return ("// Generated by scripts/build_locales.py. Edit web/locales/*.json.\n"
            + "globalThis.WattWiseLocaleManifest = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n"
            + "globalThis.WattWiseCatalogs = " + json.dumps(resources, ensure_ascii=False, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    (ROOT / "web" / "locales.js").write_text(bundle(), encoding="utf-8", newline="\n")
